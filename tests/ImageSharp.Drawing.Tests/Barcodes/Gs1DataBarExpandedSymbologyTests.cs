    /// <summary>
    /// Section 5.5.2.3.1 of the GS1 General Specifications gives Figure 5-47, which encodes
    /// (01)90614141000015(3202)000150, as 38.35 millimetres wide at an X dimension of 0.254 millimetre,
    /// 151 modules, and 34X high. No quiet zone is required.
    /// </summary>
    [Fact]
    public void Gs1DataBarExpanded_MatchesTheDimensionsOfFigure547()
    {
        LinearBarcodeSymbol symbol = Encode("(01)90614141000015(3202)000150");
        Assert.Equal(151F, symbol.WidthInModules);
        Assert.Equal(34F, symbol.HeightInModules);
        Assert.Equal(0F, symbol.LeadingQuietZone);
        Assert.Equal(0F, symbol.TrailingQuietZone);
    }

    /// <summary>
    /// Section 5.5.2.3.1: a symbol has 4 to 22 symbol characters, "a minimum of 102X wide".
    /// </summary>
    [Fact]
    public void Gs1DataBarExpanded_IsAtLeastFourSymbolCharactersWide()
        => Assert.Equal(102F, Encode("(21)1").WidthInModules);

    /// <summary>
    /// The human readable interpretation is the element strings as given, below the bars.
    /// </summary>
    [Fact]
    public void Gs1DataBarExpanded_TextPrintsTheElementStrings()
    {
        BarcodeOptions options = new() { Font = BarcodeFonts.OcrB.CreateFont(12F) };
        LinearBarcodeSymbol symbol = (LinearBarcodeSymbol)new Gs1DataBarExpandedSymbology().Encode("(01)90614141000015(3202)000150", options);
        BarcodeTextPlacement placement = Assert.Single(symbol.Text);
        Assert.Equal("(01)90614141000015(3202)000150", placement.Text);
        Assert.Equal(symbol.HeightInModules + BarcodeTextPlacement.Clearance, placement.TextEdge);
    }

    /// <summary>
    /// The compressed methods carry the GTIN of Application Identifier (01) without its check digit, so a
    /// wrong check digit is refused. A character outside the general purpose field and data longer than 21
    /// data characters are refused too.
    /// </summary>
    [Theory]
    [InlineData("(01)90614141000016(3202)000150")]
    [InlineData("(01)09521234543214")]
    [InlineData("(21)AB#")]
    [InlineData("(21)ABCDEFGHIJKLMNOPQRST(22)ABCDEFGHIJKLMNOPQRST(240)ABCDEFGHIJ")]
    [InlineData("01095212345432")]
    public void Gs1DataBarExpanded_RejectsInvalidInput(string text)
        => Assert.Throws<ArgumentException>(() => Encode(text));

    private static LinearBarcodeSymbol Encode(string text)
