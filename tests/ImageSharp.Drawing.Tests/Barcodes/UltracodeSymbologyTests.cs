    [Theory]
    [MemberData(nameof(MatchesReferenceGridData))]
    public void MatchesReferenceGrid(UltracodeErrorCorrectionLevel level, string text, int width, int height, string expected)
        => SymbolEncoder.Encode(new UltracodeSymbology(level), text, new BarcodeOptions(), (ref symbol) =>
        {
            Assert.Equal((width, height), (symbol.Columns, symbol.MatrixRows));
            Assert.Equal(expected, ColorGrid(ref symbol));
        });

    /// <summary>
    /// The largest symbol holds 282 tiles. At level EC5, 203 characters make 206 message codewords and 77 check codewords, 283 tiles, so they do not fit.
    /// </summary>
    [Fact]
    public void RejectsDataBeyondTheLargestSymbol()
        => Assert.Throws<ArgumentException>(
            () => SymbolEncoder.Encode(new UltracodeSymbology(UltracodeErrorCorrectionLevel.EC5), new string('A', 203), new BarcodeOptions()));

    /// <summary>
    /// Ultracode carries the 256 byte values, U+0000 to U+00FF.
    /// </summary>
    [Fact]
    public void RejectsCharactersAboveLatin1()
        => Assert.Throws<ArgumentException>(() => SymbolEncoder.Encode(new UltracodeSymbology(), "Ā", new BarcodeOptions()));

    /// <summary>
    /// Writes the module colours of a symbol as rows of digits separated by '|', with the digits of the reference grids.
    /// </summary>
    /// <param name="symbol">The symbol.</param>
    /// <returns>The grid.</returns>
    private static string ColorGrid(ref BarcodeSymbol symbol)
    {
        StringBuilder builder = new();
        ReadOnlySpan<BarcodeModuleColor> colors = symbol.ModuleColors;
        for (int r = 0; r < symbol.MatrixRows; r++)
        {
            if (r > 0)
            {
                builder.Append('|');
            }

            foreach (BarcodeModuleColor color in colors.Slice(r * symbol.Columns, symbol.Columns))
            {
                builder.Append(color switch
                {
                    BarcodeModuleColor.Light => '0',
                    BarcodeModuleColor.Dark => '9',
                    BarcodeModuleColor.Cyan => '1',
                    BarcodeModuleColor.Magenta => '3',
                    BarcodeModuleColor.Yellow => '5',
                    _ => '6',
                });
            }
        }

        return builder.ToString();
    }
