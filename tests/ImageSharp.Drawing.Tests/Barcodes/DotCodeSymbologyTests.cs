    /// <summary>
    /// The size and the dot grid of each symbol match the reference implementation.
    /// </summary>
    /// <param name="gs1">Whether the text is GS1 data.</param>
    /// <param name="columns">The columns asked for, or 0 for automatic.</param>
    /// <param name="rows">The rows asked for, or 0 for automatic.</param>
    /// <param name="text">The text to encode.</param>
    /// <param name="width">The columns of the symbol.</param>
    /// <param name="height">The rows of the symbol.</param>
    /// <param name="expected">The reference dot grid.</param>
    [Theory]
    [MemberData(nameof(MatchesReferenceGridData))]
    public void MatchesReferenceGrid(bool gs1, int columns, int rows, string text, int width, int height, string expected)
    {
        BarcodeSymbology symbology = (gs1, columns, rows) switch
        {
            (false, 0, _) => new DotCodeSymbology(),
            (false, _, 0) => new DotCodeSymbology(columns),
            (false, _, _) => new DotCodeSymbology(columns, rows),
            (true, 0, _) => new Gs1DotCodeSymbology(),
            (true, _, 0) => new Gs1DotCodeSymbology(columns),
            _ => new Gs1DotCodeSymbology(columns, rows),
        };

        SymbolEncoder.Encode(symbology, text, new BarcodeOptions(), (ref symbol) =>
        {
            Assert.Equal((width, height), (symbol.Columns, symbol.MatrixRows));
            Assert.Equal(expected, SymbolEncoder.ModuleGrid(ref symbol));
        });
    }

    /// <summary>
    /// A fixed size holds a fixed number of codewords, so data that needs more does not fit it.
    /// </summary>
    [Fact]
    public void RejectsDataBeyondTheSize()
        => Assert.Throws<ArgumentException>(
            () => SymbolEncoder.Encode(new DotCodeSymbology(5, 6), "This text needs more than 5 by 6 holds", new BarcodeOptions()));

    /// <summary>
    /// The columns and the rows of a DotCode symbol sum to an odd number.
    /// </summary>
    [Fact]
    public void RejectsSidesWithEvenSum()
        => Assert.Throws<ArgumentException>(() => new DotCodeSymbology(10, 10));

    /// <summary>
    /// DotCode carries the 256 byte values, U+0000 to U+00FF.
    /// </summary>
    [Fact]
    public void RejectsCharactersAboveLatin1()
        => Assert.Throws<ArgumentException>(() => SymbolEncoder.Encode(new DotCodeSymbology(), "Ā", new BarcodeOptions()));
